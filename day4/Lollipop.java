class Lollipop {
    static void unwrap() { System.out.println("Unwrapping the lollipop."); }
    static void lick() { System.out.println("Licking the lollipop."); }
    static void bite() { System.out.println("Biting the lollipop."); }
    static void finish() { System.out.println("Lollipop finished."); }
    static void disposeWrapper() { System.out.println("Wrapper disposed."); }
    static void changeFlavor() { System.out.println("Changing lollipop flavor."); }
    static void breakLollipop() { System.out.println("Breaking the lollipop."); }
    static void shareLollipop() { System.out.println("Sharing the lollipop."); }
    static void storeLollipop() { System.out.println("Storing the lollipop."); }
    static void buyLollipop() { System.out.println("Buying a lollipop."); }
	public static void main(String[] args){
	changeFlavor();
	breakLollipop();
	shareLollipop();
	storeLollipop();
	buyLollipop();
	}
}	